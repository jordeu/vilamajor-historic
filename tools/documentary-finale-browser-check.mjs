import {tourFinaleStart,tourDuration,tourShots} from '../src/tour.ts';
import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:560,height:720},reducedMotion:'reduce'});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
page.setDefaultTimeout(60000);
const opacity=()=>page.locator('#scene').getAttribute('data-photo-opacity').then(Number);
const seek=async seconds=>page.locator('#film-seek').evaluate((input,value)=>{input.value=String(value);input.dispatchEvent(new Event('input',{bubbles:true}));},seconds);
try{
 await page.goto('http://localhost:5173');
 await page.locator('#scene[data-resolution="0.25"]').waitFor();
 await page.locator('#play').click();
 await page.locator('#film-play').click();
 await page.locator('#film-chapter').selectOption(String(tourShots.length-2));
 assert.equal(await page.locator('[data-layer="terrain"]').getAttribute('aria-pressed'),'true');
 assert.equal(await opacity(),0);
 await seek(tourFinaleStart);
 await page.locator('#map-stage[data-waiting-for-photo="false"]').waitFor();
 assert.equal(await opacity(),0);
 assert.match(await page.locator('#film-evidence').textContent(),/2025.*ICGC/);
 await page.screenshot({path:'/tmp/vilamajor-finale-terrain.png',timeout:30000});
 await seek(tourFinaleStart+4);assert.equal(await opacity(),.5);
 await page.screenshot({path:'/tmp/vilamajor-finale-half.png',timeout:30000});
 await page.waitForTimeout(250);assert.equal(await opacity(),.5,'pause holds the blend');
 await page.locator('#film-play').click();
 await page.waitForFunction(()=>Number(document.getElementById('scene').dataset.photoOpacity)>.5);
 await page.locator('#film-play').click();assert.ok(await opacity()>.5,'resume continues the fade');
 await seek(tourDuration);assert.equal(await opacity(),1);
 await page.screenshot({path:'/tmp/vilamajor-finale-full.png',timeout:30000});
 await seek(tourFinaleStart-4);assert.equal(await opacity(),0);
 assert.equal(await page.locator('[data-layer="terrain"]').getAttribute('aria-pressed'),'true');
 await seek(tourFinaleStart+4);assert.equal(await opacity(),.5,'reverse and forward seeking preserves the transition');
 await page.locator('#film-exit').click();
 await page.locator('#map-stage:not(.documentary)').waitFor();
 assert.equal(await opacity(),1,'normal viewer restores full photo opacity');
 assert.equal(await page.locator('[data-layer="photo"]').getAttribute('aria-pressed'),'true');
 assert.deepEqual(errors,[]);
 console.log('PASS finale terrain → half → full photo, real photo date, pause/resume, backward seek, restored viewer, no shader errors');
}finally{await browser.close();}
